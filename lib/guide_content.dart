class GuideTip {
  final String title, level, when, steps, why, benefit, caution, next;
  const GuideTip(
    this.title,
    this.level,
    this.when,
    this.steps,
    this.why,
    this.benefit,
    this.caution,
    this.next,
  );
}

class GuideQuiz {
  final String question, answer;
  const GuideQuiz(this.question, this.answer);
}

class GuideChapter {
  final String title, subtitle, intro, route;
  final List<GuideTip> tips;
  final List<GuideQuiz> quizzes;
  final List<int> sources;
  const GuideChapter(
    this.title,
    this.subtitle,
    this.intro,
    this.route,
    this.tips,
    this.quizzes,
    this.sources,
  );
}

class GuideSource {
  final String title, url, note;
  const GuideSource(this.title, this.url, this.note);
}

